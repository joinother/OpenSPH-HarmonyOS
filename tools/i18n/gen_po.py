# 读取词条
msgs = [l.rstrip("\n") for l in open("/tmp/opensph_msgs.txt", encoding="utf-8")]

# 生成 .po
po_lines = [
    'msgid ""',
    'msgstr ""',
    '"Project-Id-Version: OpenSPH 0.4.1-ohos\\n"',
    '"Report-Msgid-Bugs-To: \\n"',
    '"POT-Creation-Date: 2026-08-27 20:30+0800\\n"',
    '"PO-Revision-Date: 2026-08-27 20:30+0800\\n"',
    '"Last-Translator: OpenSPH-HarmonyOS\\n"',
    '"Language-Team: zh_CN\\n"',
    '"Language: zh_CN\\n"',
    '"MIME-Version: 1.0\\n"',
    '"Content-Type: text/plain; charset=UTF-8\\n"',
    '"Content-Transfer-Encoding: 8bit\\n"',
    '"Plural-Forms: nplurals=1; plural=0;\\n"',
    '"\\n"',
]
translated = 0
skipped = []
for m in msgs:
    if m in T and T[m]:
        msgstr = T[m]
        translated += 1
    else:
        msgstr = ""
        skipped.append(m)
    def poesc(s):
        return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    po_lines.append("")
    po_lines.append("#: OpenSPH ui")
    po_lines.append('msgid "' + poesc(m) + '"')
    po_lines.append('msgstr "' + poesc(msgstr) + '"')

out_po = os.path.join(os.path.dirname(os.path.abspath(__file__)), "OpenSPH.zh_CN.po")
open(out_po, "w", encoding="utf-8").write("\n".join(po_lines) + "\n")
print(f"生成 {out_po}")
print(f"翻译 {translated}/{len(msgs)}，未翻译 {len(skipped)}")
print("未翻译词条:", skipped)
